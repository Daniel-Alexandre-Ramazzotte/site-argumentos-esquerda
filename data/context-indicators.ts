import type { Indicator } from "./historical";
import data from "./public-context.json";

function series(
  code: keyof typeof data,
  slug: string,
  title: string,
  category: string,
  unit: string,
  description: string,
  caveat: string,
  divisor = 1,
  irregular = false,
): Indicator {
  const source = data[code];
  return {
    slug,
    title,
    category,
    unit,
    description,
    seriesName: title,
    points: source.points.map((p) => ({ ...p, value: p.value / divisor })),
    frequency: irregular ? "irregular" : "annual",
    summary: description,
    findings: [
      { title: "Leia a definição antes de comparar", body: caveat },
      {
        title: "Histórico e cobertura",
        body: `A série importada cobre ${source.points[0].year}–${source.points.at(-1)!.year}. O filtro inicia em 1985 quando há observação disponível; o histórico completo preserva os anos anteriores. Anos sem observação não recebem valores inventados.`,
      },
      {
        title: "Uma série nacional",
        body: "Esta base é nacional. Não calculamos estados ou regiões repartindo o total do Brasil. Mudanças no tempo refletem múltiplos fatores e não identificam, isoladamente, o efeito de um governo.",
      },
    ],
    methodology: `Banco Mundial, World Development Indicators, código ${code}. Valores publicados pela fonte, sem interpolação local. ${irregular ? "Observações esparsas: lacunas permanecem visíveis no gráfico." : "Periodicidade anual."} ${description}`,
    caveat,
    sources: [
      {
        label: `Banco Mundial · ${code} · dados e metadados`,
        url: `https://data.worldbank.org/indicator/${code}?locations=BR`,
      },
      { label: "API oficial · dados utilizados", url: source.source },
    ],
  };
}
